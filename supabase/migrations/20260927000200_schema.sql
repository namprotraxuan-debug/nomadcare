create table if not exists public.content_releases (
  id               bigint generated by default as identity primary key,
  version          text not null unique,
  kind             text not null default 'medical',
  status           text not null default 'draft'
                   check (status in ('draft', 'in_review', 'approved', 'retracted')),
  notes            text,
  reviewer_round1  text,            -- team member who compiled & cross-checked sources
  approver         text,            -- medical advisor who signs round 2
  approved_at      timestamptz,
  created_at       timestamptz not null default now()
);

do $$
begin
  if not exists (select 1 from pg_constraint
                 where conname = 'content_releases_approved_signed'
                   and conrelid = 'public.content_releases'::regclass) then
    -- PDF 8.1: content without the round-2 signature must not be released.
    alter table public.content_releases add constraint content_releases_approved_signed
      check (status <> 'approved' or (nullif(btrim(approver), '') is not null and approved_at is not null));
  end if;
end $$;

