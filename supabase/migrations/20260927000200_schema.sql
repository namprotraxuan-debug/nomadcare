-- =============================================================================
-- NomadCare v2 — 0200 schema: tables, constraints, indexes, row triggers
-- Owner: P1 database. Contract: CONTRACT.md §9 (names are the contract).
-- Text columns + CHECK constraints are used instead of enums (easier to evolve).
-- Coordinates are stored as geography(…,4326); JSON APIs expose [lat,lng].
-- Idempotent: "if not exists" everywhere, triggers are dropped/re-created.
-- =============================================================================
set search_path = public, extensions;

-- ------------------------------------------------------ reference data ----
create table if not exists public.carriers (
  id    text primary key,
  name  text not null,
  sort  int  not null default 0
);

create table if not exists public.routes (
  id             text primary key,
  name           text not null,
  name_en        text,
  region         text,
  travel_mode    text not null default 'motorbike'
                 check (travel_mode in ('motorbike', 'hiking', 'mixed')),
  length_km      numeric check (length_km is null or length_km >= 0),
  color          text,
  description_vi text,
  description_en text,
  geom           geography(LineString, 4326),
  bbox           jsonb,             -- [south, west, north, east]; computed from geometry when null
  sort           int not null default 0,
  is_active      boolean not null default true,
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now()
);

create table if not exists public.route_nodes (
  id        text primary key,
  route_id  text not null references public.routes (id) on delete cascade,
  name      text not null,
  name_en   text,
  kind      text not null default 'poi'
            check (kind in ('town', 'junction', 'pass', 'trailhead', 'village', 'viewpoint', 'poi')),
  geom      geography(Point, 4326) not null
);

create table if not exists public.route_edges (
  id            text primary key,
  route_id      text not null references public.routes (id) on delete cascade,
  from_node     text not null references public.route_nodes (id) on delete cascade,
  to_node       text not null references public.route_nodes (id) on delete cascade,
  length_km     numeric not null check (length_km >= 0),   -- filled from geom when omitted
  is_connector  boolean not null default false,
  geom          geography(LineString, 4326) not null
);

-- ------------------------------------------------------------ signal ----
create table if not exists public.signal_samples (
  id            bigint generated by default as identity primary key,
  route_id      text not null references public.routes (id) on delete cascade,
  edge_id       text references public.route_edges (id) on delete set null,
  carrier       text not null references public.carriers (id),
  tech          text check (tech in ('5G', '4G', '3G', '2G', 'none')),
  rsrp_dbm      int check (rsrp_dbm is null or rsrp_dbm between -160 and -20),
  level         text not null check (level in ('likely', 'uncertain', 'lost')),  -- derived from rsrp when omitted
  geom          geography(Point, 4326) not null,
  measured_at   timestamptz not null default now(),
  source        text not null default 'team' check (source in ('team', 'community')),
  status        text not null default 'approved' check (status in ('approved', 'pending', 'rejected')),
  device_model  text,
  is_holdout    boolean not null default false,
  created_at    timestamptz not null default now()
);

create table if not exists public.signal_segments (
  id             bigint generated by default as identity primary key,
  route_id       text not null references public.routes (id) on delete cascade,
  edge_id        text not null references public.route_edges (id) on delete cascade,
  carrier        text not null references public.carriers (id),
  seq            int not null default 0,
  from_km        numeric not null check (from_km >= 0),
  to_km          numeric not null,
  level          text not null check (level in ('likely', 'uncertain', 'lost')),
  confidence     numeric check (confidence is null or confidence between 0 and 1),
  model_version  text,
  created_at     timestamptz not null default now(),
  constraint signal_segments_range check (to_km >= from_km)
);

create table if not exists public.route_accuracy (
  route_id       text not null references public.routes (id) on delete cascade,
  carrier        text not null references public.carriers (id),
  accuracy       numeric check (accuracy is null or accuracy between 0 and 1),
  holdout_n      int check (holdout_n is null or holdout_n >= 0),
  model_version  text,
  computed_at    timestamptz not null default now(),
  primary key (route_id, carrier)
);

-- ------------------------------------------------ facilities & services ----
create table if not exists public.facilities (
  id              text primary key default gen_random_uuid()::text,
  route_id        text references public.routes (id) on delete set null,
  name            text,
  type            text check (type in ('tram_y_te', 'phong_kham', 'benh_vien', 'nha_thuoc')),
  address         text,
  geom            geography(Point, 4326),
  phone           text,
  open_hours      text,
  night_shift     boolean,
  trauma_capable  boolean,
  verified_by     text,            -- name of the person who answered the verification call
  verified_at     date,
  status          text not null default 'pending' check (status in ('verified', 'pending', 'rejected')),
  source          text not null default 'team' check (source in ('team', 'community')),
  notes           text,
  is_demo         boolean not null default true,
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now()
);

-- PDF 8.1: a record only counts as verified when EVERY field is present;
-- otherwise it stays pending and is never published to devices.
do $$
begin
  if not exists (select 1 from pg_constraint
                 where conname = 'facilities_verified_complete'
                   and conrelid = 'public.facilities'::regclass) then
    alter table public.facilities add constraint facilities_verified_complete check (
      status <> 'verified' or (
            nullif(btrim(name), '')        is not null
        and nullif(btrim(address), '')     is not null
        and geom                           is not null
        and type                           is not null
        and nullif(btrim(open_hours), '')  is not null
        and night_shift                    is not null
        and trauma_capable                 is not null
        and nullif(btrim(phone), '')       is not null
        and nullif(btrim(verified_by), '') is not null
        and verified_at                    is not null
      )
    );
  end if;
end $$;

