-- ------------------------------------------------------------ helpers ----
-- "Today" in Vietnam. The database runs in UTC, but facility freshness
-- (is_stale = verified > 90 days ago, days_since_verified) is a calendar
-- notion for Vietnamese users and must match the app's local-date maths.
create or replace function app_private.today_vn()
returns date
language sql
stable
set search_path = public, extensions, pg_temp
as $$
  select (now() at time zone 'Asia/Ho_Chi_Minh')::date
$$;

-- ------------------------------------------------------- row triggers ----
-- updated_at maintenance.
create or replace function app_private.touch_updated_at()
returns trigger
language plpgsql
set search_path = public, extensions, pg_temp
as $$
begin
  new.updated_at := now();
  return new;
end $$;

do $$
declare
  t text;
begin
  foreach t in array array['routes', 'facilities', 'services', 'buddy_sessions'] loop
    execute format('drop trigger if exists %I on public.%I', t || '_touch_updated_at', t);
    execute format('create trigger %I before update on public.%I
                    for each row execute function app_private.touch_updated_at()',
                   t || '_touch_updated_at', t);
  end loop;
end $$;

-- Derived defaults: length from geometry, signal level from RSRP (CONTRACT §8:
-- likely ≥ −105 dBm; uncertain −115…−105; lost < −115 or no service).
create or replace function app_private.level_from_rsrp(p_rsrp int, p_tech text default null)
returns text
language sql
immutable
set search_path = public, extensions, pg_temp
as $$
  select case
    when p_tech = 'none' then 'lost'
    when p_rsrp is null then 'uncertain'        -- no reading: do not pretend to know
    when p_rsrp >= -105 then 'likely'
    when p_rsrp >= -115 then 'uncertain'
    else 'lost'
  end
$$;

create or replace function app_private.route_defaults()
returns trigger
language plpgsql
set search_path = public, extensions, pg_temp
as $$
begin
  if new.length_km is null and new.geom is not null then
    new.length_km := round((ST_Length(new.geom) / 1000.0)::numeric, 3);
  end if;
  return new;
end $$;

create or replace function app_private.signal_sample_defaults()
returns trigger
language plpgsql
set search_path = public, extensions, pg_temp
as $$
begin
  if new.level is null then
    new.level := app_private.level_from_rsrp(new.rsrp_dbm, new.tech);
  end if;
  return new;
end $$;

drop trigger if exists routes_defaults on public.routes;
create trigger routes_defaults before insert or update of geom, length_km on public.routes
  for each row execute function app_private.route_defaults();

drop trigger if exists route_edges_defaults on public.route_edges;
create trigger route_edges_defaults before insert or update of geom, length_km on public.route_edges
  for each row execute function app_private.route_defaults();

drop trigger if exists signal_samples_defaults on public.signal_samples;
create trigger signal_samples_defaults before insert or update of level, rsrp_dbm, tech on public.signal_samples
  for each row execute function app_private.signal_sample_defaults();
